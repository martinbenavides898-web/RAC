-- Registro de respaldos: guarda metadatos, nunca credenciales.
create table if not exists public.backup_logs (
    id bigint generated by default as identity primary key,
    backup_uuid uuid not null unique,
    backup_type text not null check (backup_type in ('manual', 'daily', 'weekly', 'pre_migration')),
    storage_target text not null,
    drive_file_id text,
    drive_folder_path text,
    file_name text not null,
    file_size_bytes bigint,
    sha256_hash text,
    manifest_json jsonb,
    verified boolean not null default false,
    status text not null default 'pending',
    created_at timestamptz not null default now()
);

alter table public.backup_logs enable row level security;
grant select, insert, update, delete on public.backup_logs to service_role;
grant usage, select on sequence public.backup_logs_id_seq to service_role;

-- Memorias seleccionadas de RAC. No guarda conversaciones completas.
create table if not exists public.coach_memories (
    id bigint generated by default as identity primary key,
    category text not null
        check (category in ('Preferencia', 'Historial', 'Lesión', 'Objetivo', 'Contexto', 'Decisión')),
    title text not null,
    content text not null,
    importance smallint not null default 3
        check (importance between 1 and 5),
    active boolean not null default true,
    source text not null default 'manual',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Análisis estructurados y reutilizables. No guarda el prompt completo.
create table if not exists public.coach_analyses (
    id bigint generated by default as identity primary key,
    analysis_type text not null
        check (analysis_type in ('entrenamiento', 'semana', 'pregunta')),
    reference_key text not null,
    input_hash text not null unique,
    request_text text not null default '',
    activity_id bigint references public.activities(id) on delete set null,
    period_start date,
    period_end date,
    response_json jsonb not null,
    model text not null,
    prompt_version text not null,
    input_tokens integer,
    output_tokens integer,
    created_at timestamptz not null default now()
);

create index if not exists coach_memories_active_idx
    on public.coach_memories(active, importance desc);

create index if not exists coach_analyses_created_idx
    on public.coach_analyses(created_at desc);

create index if not exists coach_analyses_activity_idx
    on public.coach_analyses(activity_id);

alter table public.coach_memories enable row level security;
alter table public.coach_analyses enable row level security;

grant select, insert, update, delete
on public.coach_memories, public.coach_analyses
to service_role;

grant usage, select
on all sequences in schema public
to service_role;

